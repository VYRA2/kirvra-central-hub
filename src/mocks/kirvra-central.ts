export function findDriver(id: string) {
  return drivers.find((d) => d.id === id) ?? null;
}

export function findVehicle(id: string | null) {
  return id ? (vehicles.find((v) => v.id === id) ?? null) : null;
}

export function findSession(id: string) {
  return sessions.find((s) => s.id === id) ?? null;
}

export function findAlert(id: string) {
  return [...alerts, ...alertHistory].find((a) => a.id === id) ?? null;
}
